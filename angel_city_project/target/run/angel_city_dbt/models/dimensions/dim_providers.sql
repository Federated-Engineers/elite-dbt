CREATE OR REPLACE TRANSIENT TABLE ANGEL_CITY_HEALTH_DB.DEV.DIM_PROVIDERS

AS (

    WITH PROVIDER_DETAILS AS (
        SELECT *
        FROM ANGEL_CITY_HEALTH_DB.DEV.STG_PROVIDERS

    )

    , FINAL AS (
        SELECT
            PROVIDER_ID
            , NPI_NUMBER
            , SPECIALTY_CODE
            , PROVIDER_TYPE
            , FACILITY_ID
            , HIRE_DATE
            , IS_ACTIVE
            , LOAD_TIMESTAMP
        FROM PROVIDER_DETAILS
    )

    SELECT *
    FROM FINAL
);

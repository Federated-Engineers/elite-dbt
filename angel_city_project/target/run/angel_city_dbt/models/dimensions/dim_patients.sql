CREATE OR REPLACE TRANSIENT TABLE ANGEL_CITY_HEALTH_DB.DEV.DIM_PATIENTS

AS (

    WITH PATIENT_DETAILS AS (
        SELECT *
        FROM ANGEL_CITY_HEALTH_DB.DEV.STG_PATIENTS

    )

    , FINAL AS (
        SELECT
            PATIENT_ID
            , PATIENT_FIRST_NAME
            , PATIENT_LAST_NAME
            , GENDER_CODE
            , DATE_OF_BIRTH
            , RESIDENTIAL_ZIP_CODE
            , PRIMARY_INSURANCE_ID
            , LOAD_TIMESTAMP
        FROM PATIENT_DETAILS
    )

    SELECT *
    FROM FINAL
);

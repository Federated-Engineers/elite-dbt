CREATE OR REPLACE TRANSIENT TABLE ANGEL_CITY_HEALTH_DB.DEV.MART_REVENUE_CYCLE

AS (

    SELECT
        CLAIM_ID
        , PAYER_ID
        , CLAIM_STATUS
        , TOTAL_BILLED_AMOUNT
        , AMOUNT_PAID_BY_INSURANCE
        , PATIENT_RESPONSIBILITY_AMOUNT
        , ENCOUNTER_END_TIMESTAMP
        , PROCESSED_DATE
        , datediff(
            DAY
            , ENCOUNTER_END_TIMESTAMP
            , PROCESSED_DATE
        ) AS DAYS_TO_PAYMENT
        , current_timestamp() AS LAST_UPDATED
    FROM ANGEL_CITY_HEALTH_DB.DEV.INT_CLAIMS_ACTIVITY
    WHERE CLAIM_STATUS = 'Paid'
);

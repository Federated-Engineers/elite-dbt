CREATE OR REPLACE TRANSIENT TABLE ANGEL_CITY_HEALTH_DB.DEV.FCT_DIAGNOSES

AS (

    WITH DIAGNOSES_DETAILS AS (
        SELECT *
        FROM ANGEL_CITY_HEALTH_DB.DEV.STG_DIAGNOSES

    )

    , FINAL AS (
        SELECT
            DIAGNOSIS_ID
            , ENCOUNTER_ID
            , ICD_10_CODE
            , DIAGNOSIS_RANK
            , CODING_SYSTEM
            , RECORDED_AT_TIMESTAMP
            , LOAD_TIMESTAMP
        FROM DIAGNOSES_DETAILS
    )

    SELECT *
    FROM FINAL
);

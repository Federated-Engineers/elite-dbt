CREATE OR REPLACE TRANSIENT TABLE ANGEL_CITY_HEALTH_DB.DEV.FCT_ENCOUNTERS

AS (

    WITH ENCOUNTERS_DETAILS AS (
        SELECT *
        FROM ANGEL_CITY_HEALTH_DB.DEV.STG_ENCOUNTERS

    )

    , FINAL AS (
        SELECT
            ENCOUNTER_ID
            , PATIENT_ID
            , PROVIDER_ID
            , ENCOUNTER_START_TIMESTAMP
            , ENCOUNTER_END_TIMESTAMP
            , ENCOUNTER_CLASS
            , ADMISSION_SOURCE
            , LOAD_TIMESTAMP
        FROM ENCOUNTERS_DETAILS
    )

    SELECT *
    FROM FINAL
);
